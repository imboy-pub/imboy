tablename_returns_correct_table_test_() ->
    ?WITH_MECK(elib_pg_sql, [
        {'public_tablename', 1, fun(_Table) -> <<"public.user_tag">> end}
    ], fun() ->
        Result = user_tag_repo:tablename(),
        ?assertEqual(<<"public.user_tag">>, Result)
    end).


#!/usr/bin/env bash
# IMBOY_HIRD_AUTH_REPLAY_POC_V1 — 任务专用编译（P0）。
#
# 产出：_build/hird_poc_v1/vm/ebin（imboy src，worktree HEAD 源码）
#       _build/hird_poc_v1/vm/test_ebin（本任务相关 test 模块，-DTEST）
# deps：只读复用主工作树已锁定依赖的 beam 与 include（worktree 无 deps/，
#       erlang.mk deps 目标会改写主树 deps 的 .d —— 故不经 make，直接 erlc）。
set -euo pipefail

WT="$(cd "$(dirname "$0")/../.." && pwd)"
MAIN_TREE="/Users/leeyi/project/imboy.pub/imboy"
OUT="$WT/_build/hird_poc_v1/vm"
mkdir -p "$OUT/ebin" "$OUT/test_ebin"

DEPS_EBIN_ARGS=()
for d in "$MAIN_TREE"/deps/*/ebin; do DEPS_EBIN_ARGS+=(-pa "$d"); done
DEPS_INC_ARGS=()
for d in "$MAIN_TREE"/deps/*/include; do DEPS_INC_ARGS+=(-I "$d"); done

cd "$WT"

# 全量 src（915 模块；parse_transform 需要 lager beam 在 path 上）。
# bash 数组不经 xargs 子进程传递，将 -pa/-I 参数序列化为空格前缀字符串
# 嵌入子命令（路径均无空白，安全）。
PA_STR=""
for a in "${DEPS_EBIN_ARGS[@]}"; do PA_STR+="$a "; done
PA_STR+="-pa $OUT/ebin"
INC_STR="-I include -I src -I src/lib"
for a in "${DEPS_INC_ARGS[@]}"; do INC_STR+=" $a"; done

find src -name '*.erl' -print0 |
  xargs -0 -P 8 -n 20 bash -c \
    'erlc +debug_info +"{parse_transform, lager_transform}" +nowarn_unused_function -o "$0/ebin" '"$PA_STR"' '"$INC_STR"' "$@"' \
    "$OUT"
echo "src compiled: $(ls "$OUT/ebin"/*.beam | wc -l | tr -d ' ') beams"

# 最小 imboy.app：inttest_marker_db 的 config_pg_conn/0 需要
# application:load(imboy) 成功并读 pg_conf（只 load 不 start，不触 mod 回调）。
cat > "$OUT/ebin/imboy.app" <<APP
%% generated by scripts/hird_poc_v1/compile.sh (minimal, load-only)
{application, imboy, [
  {description, "imboy PoC VM load stub"},
  {vsn, "poc-v1"},
  {modules, []},
  {registered, []},
  {applications, [kernel, stdlib, crypto, epgsql, jsone]}
]}.
APP
echo "app stub written"

# 本任务相关 test 模块（三套件 + 新增套件 + 公共助手）
TEST_MODS=(
  test/spike/agent_hird_mini_spike_tests.erl
  test/features/agent/integration/imboy_hird_gates_tests.erl
  test/features/agent/imboy_hird_acceptance_tests.erl
  test/features/agent/integration/imboy_hird_p1_auth_tool_tests.erl
  test/features/agent/integration/imboy_hird_p2_replay_tests.erl
  test/features/agent/integration/imboy_hird_p3_compare_tests.erl
  test/features/agent/integration/imboy_hird_replay_offline_tests.erl
  test/features/agent/integration/imboy_hird_poc_catalog.erl
  test/features/agent/integration/imboy_hird_poc_policy.erl
  test/features/agent/integration/imboy_hird_poc_registry.erl
  test/features/agent/integration/imboy_hird_poc_membership.erl
  test/common/inttest_marker_db.erl
)
for f in "${TEST_MODS[@]}"; do
  [ -f "$f" ] || { echo "skip (not yet created): $f"; continue; }
  erlc -DTEST=1 +debug_info +'{parse_transform, lager_transform}' \
    +nowarn_unused_function -o "$OUT/test_ebin" -pa "$OUT/ebin" -pa "$OUT/test_ebin" \
    -I include -I test -I src -I src/lib "${DEPS_INC_ARGS[@]}" "${DEPS_EBIN_ARGS[@]}" "$f"
done
echo "test compiled: $(ls "$OUT/test_ebin"/*.beam | wc -l | tr -d ' ') beams"


# 次级门禁：全部 test/ 模块编译级验证（输出独立目录，只查编译错误）。
FULL_CHECK="$OUT/test_full_check"
mkdir -p "$FULL_CHECK"
FAILS=0
while IFS= read -r f; do
  if ! erlc -DTEST=1 +debug_info +'{parse_transform, lager_transform}' \
    +nowarn_unused_function -o "$FULL_CHECK" -pa "$OUT/ebin" \
    -I include -I test -I src -I src/lib "${DEPS_INC_ARGS[@]}" "${DEPS_EBIN_ARGS[@]}" "$f" 2>/tmp/hird_poc_erlc_last.err; then
    FAILS=$((FAILS+1))
    echo "TEST_COMPILE_FAIL: $f"
    sed -n '1,4p' /tmp/hird_poc_erlc_last.err
  fi
done < <(find test -name '*.erl')
echo "full test compile check: fails=$FAILS total=$(find test -name '*.erl' | wc -l | tr -d ' ')"
[ "$FAILS" -eq 0 ]
